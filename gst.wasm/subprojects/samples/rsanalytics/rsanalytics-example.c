#include <gst/gst.h>
#include <stdio.h>

/* Generated by generate-static-plugins.py and linked into this sample. */
void gst_wasm_register_static_plugins (void);

int
main (void)
{
  gst_init (NULL, NULL);
  gst_wasm_register_static_plugins ();

  GList *features = gst_registry_get_feature_list_by_plugin (
      gst_registry_get (), "rsanalytics");
  guint n_features = g_list_length (features);

  printf ("rsanalytics features: %u\n", n_features);
  for (GList *l = features; l != NULL; l = l->next) {
    GstPluginFeature *feature = l->data;
    printf ("  %s\n", gst_plugin_feature_get_name (feature));
  }
  gst_plugin_feature_list_free (features);

  /* v1_28 registers the two ONVIF converters, combiner, splitter and the
   * seven YOLO decoders. Update this when enabling a newer feature set. */
  return n_features == 11 ? 0 : 1;
}
